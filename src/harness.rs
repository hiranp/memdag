//! Install the memdag worker into agent harnesses: a subagent on a cheap model that runs
//! `get_work` / `submit_work` batches itself, plus a short marked block in the harness's
//! instructions file so subagents (which never see the MCP server's own instructions) know
//! to delegate. Every file memdag writes is marked, so uninstall removes only its own text.

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

pub const WORKER_NAME: &str = "memdag-worker";
/// First body line of a generated worker file; uninstall deletes only files containing it.
const WORKER_MARKER: &str =
    "<!-- generated by `memdag work install`; `memdag work uninstall` removes it -->";
pub const BLOCK_START: &str = "<!-- MEMDAG_START -->";
pub const BLOCK_END: &str = "<!-- MEMDAG_END -->";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Harness {
    ClaudeCode,
    Opencode,
}

/// Where a harness keeps its files: `<project>/...` or the user-global location.
#[derive(Debug, Clone)]
pub enum Scope {
    Project(PathBuf),
    Global { home: PathBuf },
}

pub struct Paths {
    pub worker: PathBuf,
    pub instructions: PathBuf,
}

impl Harness {
    pub fn paths(self, scope: &Scope) -> Paths {
        match (self, scope) {
            (Harness::ClaudeCode, Scope::Project(p)) => Paths {
                worker: p.join(".claude/agents").join(format!("{WORKER_NAME}.md")),
                instructions: p.join("CLAUDE.md"),
            },
            (Harness::ClaudeCode, Scope::Global { home }) => Paths {
                worker: home
                    .join(".claude/agents")
                    .join(format!("{WORKER_NAME}.md")),
                instructions: home.join(".claude/CLAUDE.md"),
            },
            (Harness::Opencode, Scope::Project(p)) => Paths {
                worker: p.join(".opencode/agents").join(format!("{WORKER_NAME}.md")),
                instructions: p.join("AGENTS.md"),
            },
            (Harness::Opencode, Scope::Global { home }) => Paths {
                worker: home
                    .join(".config/opencode/agents")
                    .join(format!("{WORKER_NAME}.md")),
                instructions: home.join(".config/opencode/AGENTS.md"),
            },
        }
    }

    /// The worker subagent definition. The Claude Code tool names (`mcp__memdag__*`) assume the
    /// MCP server is registered as `memdag`, which is what `memdag mcp install` does.
    /// Claude Code accepts model aliases (`haiku`); OpenCode
    /// needs a full `provider/model` id, so without `--model` its worker inherits the
    /// session's model and the file says how to pin a cheap one.
    pub fn worker_file(self, model: Option<&str>) -> String {
        let description = "Cheap bulk worker for memdag memory upkeep (search keywords, checking STALE memories). Use it whenever memdag offers work via get_work, or for the expand_keywords / verify_stale prompts.";
        match self {
            Harness::ClaudeCode => format!(
                "---\nname: {WORKER_NAME}\ndescription: {description}\nmodel: {}\ntools: Read, Grep, Glob, mcp__memdag__get_work, mcp__memdag__submit_work\n---\n{WORKER_MARKER}\n\n{WORKER_BODY}",
                model.unwrap_or("haiku")
            ),
            Harness::Opencode => {
                let model_line = match model {
                    Some(m) => format!("model: {m}\n"),
                    None => String::new(),
                };
                let pin = if model.is_none() {
                    "\n\nNo model is pinned, so this agent uses the session's model. Pin a cheap one by re-running `memdag work install --client opencode --model <provider>/<model>` (a Haiku- or Flash-class model).\n"
                } else {
                    ""
                };
                format!(
                    "---\ndescription: {description}\nmode: subagent\n{model_line}permissions:\n  - action: edit\n    resource: \"*\"\n    effect: deny\n  - action: shell\n    resource: \"*\"\n    effect: deny\n---\n{WORKER_MARKER}\n\n{WORKER_BODY}{pin}"
                )
            }
        }
    }
}

/// The worker's standing instructions; the per-task prompt arrives with each batch.
const WORKER_BODY: &str = "You do bulk upkeep of the project's memdag memory on a small, cheap model. You are given a task (`expand` or `verify`) and optionally a number of rounds (default 3).

Repeat, at most that many rounds:
1. Call the memdag tool `get_work` with the task.
2. If `items` is empty, stop.
3. Follow the batch's `instructions` for every item. For `verify`, read only the files listed in each item's `stale_paths`, and answer `unsure` rather than guess.
4. Call `submit_work` with the task and your `results` (the `results` array from the JSON the instructions ask for).

Never edit files. Finish with one short line per round: how many items were applied and skipped.
";

/// The block added to the harness's instructions file. Short, and worded so it's harmless
/// in projects that don't use memdag (a global install applies everywhere).
pub const INSTRUCTIONS_BLOCK: &str = "<!-- MEMDAG_START -->
## memdag

When the memdag MCP server is connected and offers bulk upkeep (`get_work`, or the
`expand_keywords` / `verify_stale` prompts), don't do it with your own model: start the
`memdag-worker` subagent with the task (`expand` or `verify`). It runs on a cheap model and
fetches, processes and submits the batches itself.
<!-- MEMDAG_END -->
";

/// What install/uninstall did to one file.
#[derive(Debug, PartialEq, Eq)]
pub enum Change {
    Created,
    Updated,
    Unchanged,
    Removed,
    NotFound,
    /// Exists but isn't ours; left alone.
    Kept,
}

/// Replace a whole file atomically: temp file next to it, fsync, rename. A symlink (e.g.
/// `CLAUDE.md -> AGENTS.md`) is followed, so the real file is updated and the link survives;
/// an existing file keeps its permissions.
fn replace_file(path: &Path, text: &str) -> Result<()> {
    use std::io::Write as _;
    let target = std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
    let dir = target
        .parent()
        .filter(|d| !d.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    let tmp = dir.join(format!(
        ".{}.{}.tmp",
        target.file_name().unwrap_or_default().to_string_lossy(),
        uuid::Uuid::new_v4().simple()
    ));
    let result = (|| -> Result<()> {
        let mut f = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&tmp)?;
        f.write_all(text.as_bytes())?;
        f.sync_all()?;
        if let Ok(meta) = std::fs::metadata(&target) {
            std::fs::set_permissions(&tmp, meta.permissions())?;
        }
        std::fs::rename(&tmp, &target)?;
        Ok(())
    })();
    if result.is_err() {
        std::fs::remove_file(&tmp).ok();
    }
    result.with_context(|| format!("writing {}", target.display()))
}

/// Write `text` to `path` unless it already says exactly that.
fn write_if_changed(path: &Path, text: &str) -> Result<Change> {
    match std::fs::read_to_string(path) {
        Ok(old) if old == text => Ok(Change::Unchanged),
        Ok(_) => replace_file(path, text).map(|_| Change::Updated),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            replace_file(path, text).map(|_| Change::Created)
        }
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// Byte range of the memdag block: from the start-marker line through the end-marker line.
/// Only lines that are exactly a marker count, so prose that mentions one is never cut.
fn block_range(text: &str) -> Result<Option<(usize, usize)>> {
    let mut start = None;
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        let t = line.trim_end_matches(['\n', '\r']);
        if t == BLOCK_START {
            if start.is_some() {
                bail!("two {BLOCK_START} lines; fix the file by hand");
            }
            start = Some(offset);
        } else if t == BLOCK_END {
            let s = start.with_context(|| format!("{BLOCK_END} without {BLOCK_START}"))?;
            return Ok(Some((s, offset + line.len())));
        }
        offset += line.len();
    }
    match start {
        Some(_) => bail!("{BLOCK_START} without {BLOCK_END}; fix the file by hand"),
        None => Ok(None),
    }
}

/// Insert or refresh the memdag block, keeping the file's line endings.
pub fn upsert_block(path: &Path) -> Result<Change> {
    let old = match std::fs::read_to_string(path) {
        Ok(t) => Some(t),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let crlf = old.as_deref().is_some_and(|t| t.contains("\r\n"));
    let block = if crlf {
        INSTRUCTIONS_BLOCK.replace('\n', "\r\n")
    } else {
        INSTRUCTIONS_BLOCK.to_string()
    };
    let new = match &old {
        None => block,
        Some(text) => match block_range(text)? {
            Some((s, e)) => format!("{}{block}{}", &text[..s], &text[e..]),
            None => {
                let nl = if crlf { "\r\n" } else { "\n" };
                let sep = if text.is_empty() {
                    ""
                } else if text.ends_with(nl) {
                    nl
                } else {
                    &format!("{nl}{nl}")
                };
                format!("{text}{sep}{block}")
            }
        },
    };
    write_if_changed(path, &new)
}

/// Remove the memdag block; deletes the file if nothing else is left in it.
pub fn remove_block(path: &Path) -> Result<Change> {
    let text = match std::fs::read_to_string(path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Change::NotFound),
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let Some((s, e)) = block_range(&text)? else {
        return Ok(Change::NotFound);
    };
    let nl = if text.contains("\r\n") { "\r\n" } else { "\n" };
    // Trim only line breaks: trailing spaces can be a Markdown hard break.
    let before = text[..s].trim_end_matches(['\r', '\n']);
    let after = text[e..]
        .trim_start_matches(['\r', '\n'])
        .trim_end_matches(['\r', '\n']);
    if before.is_empty() && after.is_empty() {
        std::fs::remove_file(path)?;
        return Ok(Change::Removed);
    }
    let joined = match (before.is_empty(), after.is_empty()) {
        (false, false) => format!("{before}{nl}{nl}{after}{nl}"),
        (false, true) => format!("{before}{nl}"),
        _ => format!("{after}{nl}"),
    };
    replace_file(path, &joined)?;
    Ok(Change::Removed)
}

pub struct InstallReport {
    pub worker: (PathBuf, Change),
    pub instructions: Option<(PathBuf, Change)>,
}

pub fn install(
    harness: Harness,
    scope: &Scope,
    model: Option<&str>,
    instructions: bool,
) -> Result<InstallReport> {
    // The model goes into YAML front matter verbatim, so allow only id characters.
    if let Some(m) = model
        && (m.is_empty()
            || !m
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || "._/:#@-".contains(c)))
    {
        bail!("invalid model name '{m}' (expected an alias like haiku or provider/model)");
    }
    let paths = harness.paths(scope);
    if let Ok(existing) = std::fs::read_to_string(&paths.worker)
        && !existing.contains(WORKER_MARKER)
    {
        bail!(
            "{} exists and wasn't written by memdag; remove or rename it first",
            paths.worker.display()
        );
    }
    let worker = write_if_changed(&paths.worker, &harness.worker_file(model))?;
    let instructions = if instructions {
        Some((
            paths.instructions.clone(),
            upsert_block(&paths.instructions)?,
        ))
    } else {
        None
    };
    Ok(InstallReport {
        worker: (paths.worker, worker),
        instructions,
    })
}

pub fn uninstall(harness: Harness, scope: &Scope) -> Result<InstallReport> {
    let paths = harness.paths(scope);
    let worker = match std::fs::read_to_string(&paths.worker) {
        Ok(t) if t.contains(WORKER_MARKER) => {
            std::fs::remove_file(&paths.worker)?;
            // Only succeeds if we left the agents directory empty.
            if let Some(dir) = paths.worker.parent() {
                std::fs::remove_dir(dir).ok();
            }
            Change::Removed
        }
        Ok(_) => Change::Kept,
        Err(_) => Change::NotFound,
    };
    let instructions = remove_block(&paths.instructions)?;
    Ok(InstallReport {
        worker: (paths.worker, worker),
        instructions: Some((paths.instructions, instructions)),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn block_is_added_refreshed_and_removed_without_touching_other_text() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("AGENTS.md");
        std::fs::write(&p, "# Project\n\nMentions <!-- MEMDAG_START --> inline.\n").unwrap();
        assert_eq!(upsert_block(&p).unwrap(), Change::Updated);
        assert_eq!(upsert_block(&p).unwrap(), Change::Unchanged);
        let text = std::fs::read_to_string(&p).unwrap();
        assert_eq!(
            text.matches(BLOCK_START).count(),
            2,
            "inline mention + marker line"
        );
        assert!(text.starts_with("# Project\n\nMentions"));

        // A stale block is replaced in place.
        std::fs::write(&p, text.replace("cheap model and", "OLD")).unwrap();
        assert_eq!(upsert_block(&p).unwrap(), Change::Updated);
        assert!(!std::fs::read_to_string(&p).unwrap().contains("OLD"));

        assert_eq!(remove_block(&p).unwrap(), Change::Removed);
        assert_eq!(
            std::fs::read_to_string(&p).unwrap(),
            "# Project\n\nMentions <!-- MEMDAG_START --> inline.\n"
        );
        assert_eq!(remove_block(&p).unwrap(), Change::NotFound);

        // A block in the middle leaves the surrounding sections apart.
        std::fs::write(&p, format!("top\n\n{INSTRUCTIONS_BLOCK}\n## Next\nbody\n")).unwrap();
        remove_block(&p).unwrap();
        assert_eq!(
            std::fs::read_to_string(&p).unwrap(),
            "top\n\n## Next\nbody\n"
        );
    }

    #[test]
    fn crlf_files_keep_crlf_and_a_block_only_file_is_deleted() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("CLAUDE.md");
        std::fs::write(&p, "a\r\nb\r\n").unwrap();
        upsert_block(&p).unwrap();
        let t = std::fs::read_to_string(&p).unwrap();
        assert!(!t.replace("\r\n", "").contains('\n'), "all CRLF");
        remove_block(&p).unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "a\r\nb\r\n");

        let only = dir.path().join("NEW.md");
        assert_eq!(upsert_block(&only).unwrap(), Change::Created);
        remove_block(&only).unwrap();
        assert!(!only.exists());
    }

    #[cfg(unix)]
    #[test]
    fn a_symlinked_instructions_file_stays_a_symlink() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("AGENTS.md"), "# Agents\n").unwrap();
        let link = dir.path().join("CLAUDE.md");
        std::os::unix::fs::symlink("AGENTS.md", &link).unwrap();
        upsert_block(&link).unwrap();
        assert!(link.symlink_metadata().unwrap().file_type().is_symlink());
        let real = std::fs::read_to_string(dir.path().join("AGENTS.md")).unwrap();
        assert!(real.starts_with("# Agents\n") && real.contains(BLOCK_START));
        remove_block(&link).unwrap();
        assert!(link.symlink_metadata().unwrap().file_type().is_symlink());
        assert_eq!(std::fs::read_to_string(&link).unwrap(), "# Agents\n");
    }

    #[test]
    fn unbalanced_markers_are_refused() {
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("AGENTS.md");
        std::fs::write(&p, format!("x\n{BLOCK_START}\nhalf\n")).unwrap();
        assert!(upsert_block(&p).is_err());
        assert!(remove_block(&p).is_err());
    }

    #[test]
    fn worker_files_install_idempotently_and_never_clobber_user_agents() {
        let dir = tempfile::tempdir().unwrap();
        let scope = Scope::Project(dir.path().to_path_buf());
        let r = install(Harness::ClaudeCode, &scope, None, true).unwrap();
        assert_eq!(r.worker.1, Change::Created);
        let text = std::fs::read_to_string(&r.worker.0).unwrap();
        assert!(text.starts_with("---\nname: memdag-worker\n"));
        assert!(text.contains("\nmodel: haiku\n") && text.contains("mcp__memdag__submit_work"));
        assert_eq!(
            install(Harness::ClaudeCode, &scope, None, true)
                .unwrap()
                .worker
                .1,
            Change::Unchanged
        );
        assert_eq!(
            install(Harness::ClaudeCode, &scope, Some("sonnet"), false)
                .unwrap()
                .worker
                .1,
            Change::Updated
        );

        assert!(install(Harness::ClaudeCode, &scope, Some("haiku\nevil: yes"), false).is_err());
        assert!(install(Harness::ClaudeCode, &scope, Some("a: b"), false).is_err());
        let oc = install(Harness::Opencode, &scope, Some("google/gemini-flash"), true).unwrap();
        let text = std::fs::read_to_string(&oc.worker.0).unwrap();
        assert!(text.contains("mode: subagent\nmodel: google/gemini-flash\n"));
        assert!(dir.path().join("AGENTS.md").is_file());

        let mine = dir.path().join(".claude/agents/memdag-worker.md");
        std::fs::write(&mine, "---\nname: memdag-worker\n---\nmy own agent\n").unwrap();
        assert!(install(Harness::ClaudeCode, &scope, None, false).is_err());
        let u = uninstall(Harness::ClaudeCode, &scope).unwrap();
        assert_eq!(u.worker.1, Change::Kept);
        assert!(mine.exists());

        let u = uninstall(Harness::Opencode, &scope).unwrap();
        assert_eq!(u.worker.1, Change::Removed);
        assert!(!dir.path().join("AGENTS.md").exists());
        assert!(
            !dir.path().join(".opencode/agents").exists(),
            "empty dir removed"
        );
    }
}
